const messages: Record<Locale, Messages> = {
  [Locale.EN]: en,
  [Locale.AR]: ar,
  [Locale.FR]: fr,
};

export type StorefrontMessages = Messages;

export function getMessages(locale: Locale | string): Messages {
  if (locale === Locale.AR || locale === 'ar') return messages[Locale.AR];
  if (locale === Locale.FR || locale === 'fr') return messages[Locale.FR];
  return messages[Locale.EN];
}
